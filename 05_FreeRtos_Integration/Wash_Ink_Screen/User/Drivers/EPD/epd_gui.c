/* ================================================================
 * 字体参数表
 * ================================================================ */
typedef struct {
    uint8_t  width;   /* 字符宽度（像素）*/
    uint8_t  height;  /* 字符高度（像素）*/
    uint8_t  bytes;   /* 每个字模字节数  */
} FontParam;

static const FontParam s_font_params[2] = {
    [FONT_16X16] = {16, 16, 32},
    [FONT_24X24] = {24, 24, 72},
};

/* ================================================================
 * 全局画布
 * ================================================================ */
EPD_Canvas g_canvas;

/* ================================================================
 * 画布基础操作
 * ================================================================ */

void Canvas_Init(uint8_t *buf, uint16_t rotate, uint16_t bg_color)
{
    g_canvas.image      = buf;
    g_canvas.width_mem  = EPD_WIDTH;   /* 152 */
    g_canvas.height_mem = EPD_HEIGHT;  /* 296 */
    g_canvas.width_byte = EPD_WIDTH / 8u;  /* 19 */
    g_canvas.rotate     = rotate;
    g_canvas.bg_color   = bg_color;
}

void Canvas_Clear(uint8_t color)
{
    memset(g_canvas.image, color, (size_t)g_canvas.width_byte * g_canvas.height_mem);
}

/* 坐标映射（Rotate=0，横屏）：
 *   x = 水平位置 (0..EPD_HEIGHT-1 = 0..295)
 *   y = 垂直位置 (0..EPD_WIDTH-1  = 0..151)
 *   物理行 = x，物理列 = y
 *   帧缓冲地址 = y/8 + x * width_byte
 */
void Canvas_SetPixel(uint16_t x, uint16_t y, uint8_t color)
{
    uint16_t phys_row, phys_col;

    switch (g_canvas.rotate) {
        case 0:
            phys_row = x;
            phys_col = y;
            break;
        case 90:
            phys_row = g_canvas.width_mem - 1u - y;
            phys_col = x;
            break;
        case 180:
            phys_row = g_canvas.height_mem - 1u - x;
            phys_col = g_canvas.width_mem  - 1u - y;
            break;
        case 270:
            phys_row = y;
            phys_col = g_canvas.height_mem - 1u - x;
            break;
        default:
            return;
    }

    /* 边界检查 */
    if (phys_row >= g_canvas.height_mem || phys_col >= g_canvas.width_mem) return;

    uint32_t addr = (uint32_t)(phys_col / 8u) + (uint32_t)phys_row * g_canvas.width_byte;
    uint8_t  bit  = (uint8_t)(0x80u >> (phys_col % 8u));

    if (color == GUI_BLACK)
        g_canvas.image[addr] &= ~bit;   /* 清零 = 黑色 */
    else
        g_canvas.image[addr] |= bit;    /* 置一 = 白色 */
}

/* ================================================================
 * ASCII 字符显示
 *   FONT_16X16 → asc2_1608 ( 8×16，列优先，8列/段，2段共16字节)
 *   FONT_24X24 → asc2_2412 (12×24，列优先，12列/段，3段共36字节)
 *
 * 两种字体均为同一布局规律：每字节代表一列的8行（LSB=顶），
 * 满 cols 列后换下一段（y 偏移 +8）。
 * ================================================================ */
void GUI_ShowChar(uint16_t x, uint16_t y, char ch, FontSize fs, uint8_t color)
{
    uint8_t idx = (uint8_t)((uint8_t)ch - 0x20u);
    if (idx >= 95u) return;

    uint16_t x0 = x;
    uint16_t y0 = y;

    if (fs == FONT_16X16) {
        for (uint8_t i = 0; i < 16u; i++) {
            uint8_t data = s_ascii_1608[idx][i];
            for (uint8_t m = 0; m < 8u; m++) {
                if (data & 0x01u) Canvas_SetPixel(x, y, color);
                data >>= 1;
                y++;
            }
            x++;
            if ((x - x0) == 8u) { x = x0; y0 += 8u; }
            y = y0;
        }
    } else {
        for (uint8_t i = 0; i < 36u; i++) {
            uint8_t data = s_ascii_2412[idx][i];
            for (uint8_t m = 0; m < 8u; m++) {
                if (data & 0x01u) Canvas_SetPixel(x, y, color);
                data >>= 1;
                y++;
            }
            x++;
            if ((x - x0) == 12u) { x = x0; y0 += 8u; }
            y = y0;
        }
    }
}

void GUI_ShowString(uint16_t x, uint16_t y, const char *str, FontSize fs, uint8_t color)
{
    uint16_t char_w = (fs == FONT_16X16) ? 8u : 12u;
    while (*str) {
        GUI_ShowChar(x, y, *str, fs, color);
        x += char_w;
        str++;
    }
}

void GUI_ShowNum(uint16_t x, uint16_t y, uint32_t num, uint8_t digits, FontSize fs, uint8_t color)
{
    uint16_t char_w = (fs == FONT_16X16) ? 8u : 12u;
    uint32_t div = 1u;
    for (uint8_t i = 1u; i < digits; i++) div *= 10u;

    for (uint8_t i = 0; i < digits; i++) {
        uint8_t d = (uint8_t)(num / div % 10u);
        GUI_ShowChar(x, y, (char)('0' + d), fs, color);
        x += char_w;
        div /= 10u;
    }
}

/* ================================================================
 * GBK 中文显示（从 W25Q128 Flash 读字模）
 *
 * GBK 地址计算：
 *   有效范围：GBKH = 0x81..0xFE，GBKL = 0x40..0xFE（不含 0x7F）
 *   每行 190 个字符（GBKL 0x40-0x7E 共 63 个 + 0x80-0xFE 共 127 个）
 *   offset = (GBKH - 0x81) * 190 + (GBKL < 0x7F ? GBKL-0x40 : GBKL-0x41)
 *   flash_addr = base + offset * bytes_per_char
 *
 * 字模格式：行优先，每字节 8 个水平像素（LSB = 行内最左像素）
 * ================================================================ */
void GUI_ShowChinese(uint16_t x, uint16_t y, const uint8_t *gbk2, FontSize fs, uint8_t color)
{
    uint8_t  gbkh = gbk2[0];
    uint8_t  gbkl = gbk2[1];
    uint8_t  buf[72];   /* 最大 24×24 = 72 字节 */
    uint32_t offset, flash_addr;
    uint16_t x0 = x;
    const FontParam *fp = &s_font_params[fs];

    /* GBK 编码合法性校验 */
    if (gbkh < 0x81u || gbkh > 0xFEu ||
        gbkl < 0x40u || gbkl > 0xFEu || gbkl == 0x7Fu) return;

    /* 计算字模在字库中的偏移 */
    uint32_t row_off = (gbkl < 0x7Fu) ? (uint32_t)(gbkl - 0x40u)
                                       : (uint32_t)(gbkl - 0x41u);
    offset = (uint32_t)(gbkh - 0x81u) * 190u + row_off;

    flash_addr = ((fs == FONT_16X16) ? W25Q128_FONT16_ADDR : W25Q128_FONT24_ADDR)
                 + offset * fp->bytes;

    /* 从 Flash 读取字模 */
    W25Q128_Read(buf, flash_addr, fp->bytes);

    /* 绘制字模（行优先，每字节 LSB 为行首像素） */
    for (uint8_t i = 0; i < fp->bytes; i++) {
        for (uint8_t j = 0; j < 8u; j++) {
            if (buf[i] & (0x01u << j)) Canvas_SetPixel(x, y, color);
            x++;
            if ((x - x0) >= fp->width) {
                x = x0;
                y++;
                break;
            }
        }
    }
}

/* ================================================================
 * GUI_ShowText — GBK 混合字符串显示（ASCII + 汉字自动识别）
 *
 * 字节判断规则（与 GBK 编码兼容）：
 *   byte < 0x80           → 单字节 ASCII
 *   0x81 <= byte <= 0xFE  → 双字节 GBK 汉字（取连续两个字节）
 * ================================================================ */
void GUI_ShowText(uint16_t x, uint16_t y, const uint8_t *str, FontSize fs, uint8_t color)
{
    uint16_t ascii_w = (fs == FONT_16X16) ? 8u : 12u;
    uint16_t cjk_w   = (fs == FONT_16X16) ? 16u : 24u;

    while (str[0] != 0x00u) {
        if (str[0] < 0x80u) {
            /* ASCII 单字节 */
            GUI_ShowChar(x, y, (char)str[0], fs, color);
            x  += ascii_w;
            str += 1u;
        } else {
            /* GBK 双字节汉字：需要第二字节合法 */
            if (str[1] >= 0x40u && str[1] <= 0xFEu && str[1] != 0x7Fu) {
                GUI_ShowChinese(x, y, str, fs, color);
                x  += cjk_w;
                str += 2u;
            } else {
                /* 非法序列，跳过首字节 */
                str += 1u;
            }
        }
    }
}

/* GBK 字符串显示（str 以单个 '\0' 字节结尾，每字占 2 字节） */
void GUI_ShowChineseStr(uint16_t x, uint16_t y, const uint8_t *str, FontSize fs, uint8_t color)
{
    const FontParam *fp = &s_font_params[fs];
    while (str[0] != 0x00u && str[1] != 0x00u) {
        GUI_ShowChinese(x, y, str, fs, color);
        x  += fp->width;   /* 水平步进一个字符宽度 */
        str += 2u;
    }
}
